#!/usr/bin/env bash
# Local QEMU lab that mimics the HPC layout from config/inventory:
#   - one isolated L2 "cluster network" (a rootless VDE switch)
#   - the login node additionally has a NAT uplink (internet + ssh port-forward)
#   - admin and compute nodes have NO route to the internet
# Usage: lab/lab.sh up | down | destroy | status | ssh <host> [cmd] | console <host>
#        lab/lab.sh reprovision <host>   wipe a node's disk and boot it fresh, like HPCM
#                                        re-provisioning it (the admin node's persistent disk is kept)
. "$(cd "$(dirname "$0")/.." && pwd)/lib/common.sh"
. "$HPC_ROOT/lab/lab.env"

LAB_DIR="$HPC_ROOT/.lab"
BASE_IMG="$CACHE_DIR/lab/$(basename "$LAB_BASE_IMAGE_URL")"
VDE_SOCK="$LAB_DIR/vde.ctl"
HSN_SOCK="$LAB_DIR/vde-hsn.ctl"
SSH_CONFIG="$LAB_DIR/ssh_config"
FIRMWARE="$(dirname "$(command -v qemu-system-aarch64)")/../share/qemu/edk2-aarch64-code.fd"

size_of() { echo "$LAB_SIZES" | awk -v h="$1" -v c="$2" '$1==h {print $c}'; }
mac_of()  { printf '52:54:00:10:00:%02x' "$(host_ip "$1" | awk -F. '{print $4}')"; }
hsn_mac_of() { printf '52:54:00:20:00:%02x' "$(host_ip "$1" | awk -F. '{print $4}')"; }
hsn_ip_of()  { echo "${LAB_HSN_CIDR%.*/*}.$(host_ip "$1" | awk -F. '{print $4}')"; }
is_up()   { [ -f "$LAB_DIR/$1/pid" ] && kill -0 "$(cat "$LAB_DIR/$1/pid")" 2>/dev/null; }

ensure_prereqs() {
  need qemu-system-aarch64 qemu-img vde_switch hdiutil ssh-keygen curl
  [ "$ARCH" = arm64 ] || die "the lab uses hardware virtualisation and only runs ARCH=arm64 guests"
  mkdir -p "$LAB_DIR" "$(dirname "$BASE_IMG")"
  if [ ! -f "$BASE_IMG" ]; then
    step "downloading base image"
    curl -fL --retry 3 -o "$BASE_IMG.part" "$LAB_BASE_IMAGE_URL" && mv "$BASE_IMG.part" "$BASE_IMG"
  fi
  [ -f "$LAB_DIR/id_ed25519" ] || ssh-keygen -q -t ed25519 -N '' -C hpc-lab -f "$LAB_DIR/id_ed25519"
}

write_ssh_config() {
  local login h
  login=$(hosts_by_role login | head -1)
  {
    echo "# generated by lab/lab.sh"
    echo "Host $login"
    echo "  HostName 127.0.0.1"
    echo "  Port $LAB_SSH_PORT"
    for h in $(all_hosts); do
      [ "$h" = "$login" ] && continue
      echo "Host $h $(host_ip "$h")"
      echo "  HostName $(host_ip "$h")"
      echo "  ProxyJump $login"
    done
    echo "Host *"
    echo "  User $LAB_ADMIN_USER"
    echo "  IdentityFile $LAB_DIR/id_ed25519"
    echo "  IdentitiesOnly yes"
    echo "  UserKnownHostsFile $LAB_DIR/known_hosts"
    echo "  StrictHostKeyChecking accept-new"
    echo "  ControlMaster auto"
    echo "  ControlPath /tmp/hpc-lab-%C"
    echo "  ControlPersist 10m"
    echo "  ServerAliveInterval 30"
  } >"$SSH_CONFIG"
}

start_switch() { # management network + high-speed network, one VDE switch each
  if ! { [ -f "$LAB_DIR/vde.pid" ] && kill -0 "$(cat "$LAB_DIR/vde.pid")" 2>/dev/null; }; then
    rm -rf "$VDE_SOCK"
    vde_switch -s "$VDE_SOCK" -M "$LAB_DIR/vde.mgmt" -p "$LAB_DIR/vde.pid" -d
  fi
  if ! { [ -f "$LAB_DIR/vde-hsn.pid" ] && kill -0 "$(cat "$LAB_DIR/vde-hsn.pid")" 2>/dev/null; }; then
    rm -rf "$HSN_SOCK"
    vde_switch -s "$HSN_SOCK" -M "$LAB_DIR/vde-hsn.mgmt" -p "$LAB_DIR/vde-hsn.pid" -d
  fi
}

make_seed() { # cloud-init NoCloud seed: deploy user, static cluster IP
  local h="$1" d="$LAB_DIR/$1" role ip gw dns login_ip
  role=$(host_role "$h"); ip=$(host_ip "$h"); login_ip=$(host_ip "$(hosts_by_role login | head -1)")
  rm -rf "$d/seed"; mkdir -p "$d/seed"
  cat >"$d/seed/meta-data" <<META
instance-id: $h-$(date +%s)
local-hostname: $h
META
  cat >"$d/seed/user-data" <<USER
#cloud-config
fqdn: $h.$CLUSTER_DOMAIN
manage_etc_hosts: false
ssh_pwauth: false
users:
  - name: $LAB_ADMIN_USER
    gecos: deploy user
    groups: wheel
    sudo: "ALL=(ALL) NOPASSWD:ALL"
    shell: /bin/bash
    lock_passwd: true
    ssh_authorized_keys:
      - $(cat "$LAB_DIR/id_ed25519.pub")
growpart: {mode: auto, devices: ["/"]}
USER
  if [ "$role" = admin ]; then # persistent disk (vdc): formatted once, kept across reprovision
    cat >>"$d/seed/user-data" <<USER
# (not fs_setup: with partition none it runs mkfs -f even on an existing filesystem)
bootcmd:
  - [sh, -c, "blkid /dev/vdc >/dev/null || mkfs.xfs -L hpcpersist /dev/vdc"]
mounts:
  - [/dev/vdc, $LAB_PERSIST_MOUNT, xfs, "defaults,nofail", "0", "2"]
USER
  fi
  {
    echo "version: 2"
    echo "ethernets:"
    if [ "$role" = login ]; then
      echo "  cluster:"
      echo "    match: {macaddress: \"$(mac_of "$h")\"}"
      echo "    addresses: [$ip/${CLUSTER_CIDR#*/}]"
      # The uplink provides the default route; cluster names come from /etc/hosts.
      echo "  uplink:"
      echo "    match: {macaddress: \"52:54:00:99:00:01\"}"
      echo "    dhcp4: true"
    else
      echo "  mgmt0:"
      echo "    match: {macaddress: \"$(mac_of "$h")\"}"
      echo "    set-name: mgmt0"
      echo "  $LAB_HSN_IFACE:"
      echo "    match: {macaddress: \"$(hsn_mac_of "$h")\"}"
      echo "    set-name: $LAB_HSN_IFACE"
      echo "    addresses: [$(hsn_ip_of "$h")/${LAB_HSN_CIDR#*/}]"
      echo "bonds:"
      echo "  $LAB_MGMT_IFACE:"
      echo "    interfaces: [mgmt0]"
      echo "    parameters: {mode: active-backup, mii-monitor-interval: 100}"
      echo "    addresses: [$ip/${CLUSTER_CIDR#*/}]"
      # Air-gapped: the default route points at the login node, which does not
      # forward. It only exists so Kubernetes can pick a node interface.
      echo "    routes: [{to: 0.0.0.0/0, via: $login_ip}]"
      echo "    nameservers: {addresses: [$(admin_ip)], search: [$CLUSTER_DOMAIN]}"
    fi
  } >"$d/seed/network-config"
  rm -f "$d/seed.iso"
  hdiutil makehybrid -quiet -o "$d/seed.iso" -iso -joliet -default-volume-name cidata "$d/seed"
}

start_vm() {
  local h="$1" d="$LAB_DIR/$1" role
  role=$(host_role "$h")
  is_up "$h" && { info "$h already running"; return; }
  mkdir -p "$d"
  if [ ! -f "$d/disk.qcow2" ]; then
    qemu-img create -q -f qcow2 -F qcow2 -b "$BASE_IMG" "$d/disk.qcow2" "$(size_of "$h" 4)G"
    make_seed "$h"
  fi
  if [ "$role" = admin ] && [ ! -f "$d/persist.qcow2" ]; then
    qemu-img create -q -f qcow2 "$d/persist.qcow2" "${LAB_PERSIST_GB}G"
  fi
  set -- -name "$h" -machine virt,accel=hvf -cpu host \
    -smp "$(size_of "$h" 2)" -m "$(size_of "$h" 3)" -bios "$FIRMWARE" \
    -drive "if=virtio,file=$d/disk.qcow2,format=qcow2,discard=unmap" \
    -drive "if=virtio,file=$d/seed.iso,format=raw,readonly=on" \
    -device virtio-rng-pci -display none -serial "file:$d/console.log" \
    -monitor "unix:$d/monitor.sock,server,nowait" -pidfile "$d/pid" -daemonize
  [ "$role" = admin ] && set -- "$@" -drive "if=virtio,file=$d/persist.qcow2,format=qcow2,discard=unmap"
  if [ "$role" = login ]; then
    set -- "$@" -device virtio-net-pci,netdev=wan,mac=52:54:00:99:00:01 \
      -netdev "user,id=wan,hostfwd=tcp:127.0.0.1:$LAB_SSH_PORT-:22"
  fi
  set -- "$@" -device "virtio-net-pci,netdev=cl,mac=$(mac_of "$h")" -netdev "vde,id=cl,sock=$VDE_SOCK"
  if [ "$role" != login ]; then
    set -- "$@" -device "virtio-net-pci,netdev=hsn,mac=$(hsn_mac_of "$h")" -netdev "vde,id=hsn,sock=$HSN_SOCK"
  fi
  qemu-system-aarch64 "$@"
  info "$h started ($(size_of "$h" 2) vcpu, $(size_of "$h" 3) MiB)"
}

stop_vm() {
  local h="$1" pid
  is_up "$h" || return 0
  pid=$(cat "$LAB_DIR/$h/pid")
  hssh -o ConnectTimeout=5 "$h" 'sudo -n systemctl poweroff' >/dev/null 2>&1 || true
  local i=0; while kill -0 "$pid" 2>/dev/null && [ $i -lt 45 ]; do sleep 1; i=$((i+1)); done
  kill "$pid" 2>/dev/null || true
  info "$h stopped"
}

cmd_up() {
  ensure_prereqs; write_ssh_config; start_switch
  step "starting lab VMs"
  local h login; login=$(hosts_by_role login | head -1)
  start_vm "$login"                      # jump host first
  for h in $(all_hosts); do [ "$h" = "$login" ] || start_vm "$h"; done
  step "waiting for ssh + cloud-init"
  for h in $login $(all_hosts | grep -v "^$login\$"); do
    wait_for "ssh on $h" 300 hssh -o ConnectTimeout=5 "$h" true
    hssh "$h" 'sudo -n cloud-init status --wait >/dev/null 2>&1 || true'
    ok "$h is up"
  done
}

cmd_down() {
  local h
  for h in $(all_hosts | grep -v "^$(hosts_by_role login | head -1)\$") $(hosts_by_role login); do stop_vm "$h"; done
  for p in vde vde-hsn; do [ -f "$LAB_DIR/$p.pid" ] && kill "$(cat "$LAB_DIR/$p.pid")" 2>/dev/null || true; done
  rm -f /tmp/hpc-lab-* 2>/dev/null || true
}

cmd_destroy() {
  local h
  for h in $(all_hosts); do
    if is_up "$h"; then kill "$(cat "$LAB_DIR/$h/pid")" 2>/dev/null || true; fi
    rm -rf "${LAB_DIR:?}/$h"
  done
  for p in vde vde-hsn; do [ -f "$LAB_DIR/$p.pid" ] && kill "$(cat "$LAB_DIR/$p.pid")" 2>/dev/null || true; done
  rm -rf "$LAB_DIR/known_hosts" "$VDE_SOCK" "$HSN_SOCK" "$LAB_DIR"/vde*.pid "$LAB_DIR"/vde*.mgmt /tmp/hpc-lab-* 2>/dev/null || true
  info "lab VMs and disks removed (ssh key, base image and bundle cache kept)"
}

cmd_reprovision() { # new root disk + new cloud-init instance; persist.qcow2 survives
  local h="$1" d="$LAB_DIR/$1" pid
  [ -n "$(host_role "$h")" ] || die "unknown host $h"
  [ "$(host_role "$h")" != login ] || die "$h is the jump host; reprovision cluster nodes only"
  ensure_prereqs; write_ssh_config; start_switch
  step "re-provisioning $h (root disk wiped)"
  if is_up "$h"; then pid=$(cat "$d/pid"); kill "$pid" 2>/dev/null || true
    while kill -0 "$pid" 2>/dev/null; do sleep 1; done; fi
  rm -rf "$d/disk.qcow2" "$d/seed" "$d/seed.iso" "$d/console.log" "$d/pid"
  ssh-keygen -q -R "$h" -f "$LAB_DIR/known_hosts" >/dev/null 2>&1 || true
  ssh-keygen -q -R "$(host_ip "$h")" -f "$LAB_DIR/known_hosts" >/dev/null 2>&1 || true
  rm -f /tmp/hpc-lab-* 2>/dev/null || true
  start_vm "$h"
  wait_for "ssh on $h" 300 hssh -o ConnectTimeout=5 "$h" true
  hssh "$h" 'sudo -n cloud-init status --wait >/dev/null 2>&1 || true'
  ok "$h is back with a fresh OS"
}

cmd_status() {
  local h
  for h in $(all_hosts); do
    if is_up "$h"; then printf '%-4s %-8s %-12s running (pid %s)\n' "$h" "$(host_role "$h")" "$(host_ip "$h")" "$(cat "$LAB_DIR/$h/pid")"
    else printf '%-4s %-8s %-12s stopped\n' "$h" "$(host_role "$h")" "$(host_ip "$h")"; fi
  done
}

case "${1:-}" in
  up) cmd_up ;;
  down) cmd_down ;;
  destroy) cmd_destroy ;;
  status) cmd_status ;;
  reprovision) [ $# -eq 2 ] || die "usage: lab.sh reprovision <host>"; cmd_reprovision "$2" ;;
  ssh) shift; [ $# -ge 1 ] || die "usage: lab.sh ssh <host> [command]"; exec ssh -F "$SSH_CONFIG" "$@" ;;
  console) [ $# -eq 2 ] || die "usage: lab.sh console <host>"; exec tail -n 50 -f "$LAB_DIR/$2/console.log" ;;
  *) die "usage: lab.sh up | down | destroy | status | reprovision <host> | ssh <host> [cmd] | console <host>" ;;
esac
